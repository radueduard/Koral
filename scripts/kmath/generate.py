def default_value(lang, p):
    if p.default == "Epsilon":
        return "DEpsilon" if p.ty[0] == "d" else "Epsilon"
    if p.default == "inf":
        return f"{CS_SCALAR[p.ty[0]]}.PositiveInfinity" if lang == "cs" else f"{KT_SCALAR[p.ty[0]]}.POSITIVE_INFINITY"
    raise SystemExit(p.default)


def raw_body(inst, lang):
    raw = inst.fn.raw[lang]
    if isinstance(raw, dict):
        raw = raw.get(inst.t, raw.get(""))
    if isinstance(raw, str):
        raw = [raw]
    T = (CS_SCALAR if lang == "cs" else KT_SCALAR)[inst.t]
    out = []
    for line in raw:
        line = line.replace("$T", T).replace("$0", literal(0, inst.t, lang))
        line = re.sub(r"@\{([^}]*)\}", lambda m: literal(float(m.group(1)), inst.t, lang), line)
        out.append(line)
    return out


def dsl_body(inst):
    body = inst.fn.body
    if isinstance(body, dict):
        body = body.get(inst.t, body.get(""))
    return body


def zero_of(lang, ty):
    if len(ty) == 1:
        return literal(0, ty[0], lang) if ty[0] != "b" else "false"
    z = literal(0, ty[0], lang) if ty[0] != "b" else "false"
    return f"new {type_name(lang, ty)}({z})" if lang == "cs" else f"{type_name(lang, ty)}({z})"


# ---- C# -----------------------------------------------------------------------------------------------------

def cs_ident(name):
    return "@" + name if name in CS_KEYWORDS else name


def cs_doc(text, indent="    "):
    text = text and text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return [f"{indent}/// <summary>{text}</summary>"] if text else []


def cs_function(inst, documented):
    L = []
    if inst.fn.doc and inst.fn.doc not in documented:
        documented.add(inst.fn.doc)
        L += cs_doc(inst.fn.doc)
    params = []
    for p in inst.params:
        s = f"{'out ' if p.mode == 'out' else 'ref ' if p.mode == 'ref' else ''}{type_name('cs', p.ty)} {cs_ident(p.name)}"
        if p.default:
            s += f" = {default_value('cs', p)}"
        params.append(s)
    ret = type_name("cs", inst.ret) if inst.ret else "void"
    sig = f"    public static {ret} {inst.fn.name}({', '.join(params)})"
    if inst.how == "map":
        n = inst.n
        outs = [p for p in inst.params if p.mode]
        calls = []
        for c in XYZW[:n]:
            args = []
            for p in inst.params:
                if p.mode:
                    args.append(f"out var {p.name}{c.upper()}")
                elif p.mapped:
                    args.append(f"{cs_ident(p.name)}.{c.upper()}")
                else:
                    args.append(cs_ident(p.name))
            calls.append(f"{inst.fn.name}({', '.join(args)})")
        if not outs:
            L.append(f"{sig} => new {type_name('cs', inst.ret)}({', '.join(calls)});")
        else:
            L.append(sig)
            L.append("    {")
            if inst.ret:
                L.append(f"        var r = new {type_name('cs', inst.ret)}({', '.join(calls)});")
            else:
                L += [f"        {c};" for c in calls]
            for p in outs:
                L.append(f"        {p.name} = new {type_name('cs', p.ty)}({', '.join(p.name + c.upper() for c in XYZW[:n])});")
            if inst.ret:
                L.append("        return r;")
            L.append("    }")
        return L
    if inst.fn.raw:
        lines = raw_body(inst, "cs")
        if len(lines) == 1 and lines[0].startswith("="):
            L.append(f"{sig} => {lines[0][1:]};")
        else:
            L += [sig, "    {"] + [f"        {line}" for line in lines] + ["    }"]
        return L
    lines = dsl.body("cs", inst.t, inst.n, dsl_body(inst), 8)
    if len(lines) == 1 and lines[0].strip().startswith("return "):
        L.append(f"{sig} => {lines[0].strip()[7:]}")
    else:
        L += [sig, "    {"] + lines + ["    }"]
    return L



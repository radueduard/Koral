#!/usr/bin/env python3
"""
kmath's generated code, for every language from one description, so all of them are the same API:
  - C++: the swizzles of kor::Vec (include/kmath/detail/swizzle{2,3,4}.inl);
  - C: the vector and matrix types and every GLSL-chapter function (the generated half of koral_math_c.h,
    and src/core/capi/math_glsl.cpp, whose exports wrap the C++ templates);
  - C#: the vector and matrix types and KMath's GLSL chapters (bindings/csharp/src/Koral/Math/Generated);
  - Kotlin: the same (bindings/kotlin/koral/src/main/kotlin/koral/math/generated).
The functions are spec.py's; the bodies of the C# and Kotlin ones are its little language (dsl.py), so the
two ports do their arithmetic in C++'s order and agree with it bit for bit where IEEE says they must.
`--check` (a ctest) fails when a generated file is stale.
"""
import itertools, pathlib, re, sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import dsl  # noqa: E402
import spec  # noqa: E402
from dsl import literal, lower_camel, vec_name  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = {}   # path -> text
HEADER_CS = "// <auto-generated> by scripts/kmath/generate.py: do not edit. </auto-generated>"
HEADER_C = "/* <auto-generated> by scripts/kmath/generate.py: do not edit. </auto-generated> */"
CS_DIR = "bindings/csharp/src/Koral/Math/Generated"
KT_DIR = "bindings/kotlin/koral/src/main/kotlin/koral/math/generated"
XYZW = "xyzw"


def emit(path, text):
    OUT[ROOT / path] = text


def snake(name):
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    s = re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", "_", s)
    return s.lower()


# ---- types ---------------------------------------------------------------------------------------------------

SCALARS = "fdiub"
C_SCALAR = {"f": "float", "d": "double", "i": "int32_t", "u": "uint32_t", "b": "bool", "h": "uint16_t"}
CPP_SCALAR = {"f": "float", "d": "double", "i": "kor::i32", "u": "kor::u32", "b": "bool", "h": "kor::u16"}
CS_SCALAR = {"f": "float", "d": "double", "i": "int", "u": "uint", "b": "bool", "h": "ushort"}
KT_SCALAR = {"f": "Float", "d": "Double", "i": "Int", "u": "UInt", "b": "Boolean", "h": "UShort"}
C_PREFIX = {"f": "float", "d": "double", "i": "int", "u": "uint", "b": "bool"}
MAT_PREFIX = {"f": "", "d": "D"}


def mat_name(t, c, r):
    return f"{MAT_PREFIX[t]}Mat{c}" if c == r else f"{MAT_PREFIX[t]}Mat{c}x{r}"


def type_name(lang, ty):
    """ty: (code,) scalar or (code, n) vector or (code, c, r) matrix."""
    if len(ty) == 1:
        return {"c": C_SCALAR, "cpp": CPP_SCALAR, "cs": CS_SCALAR, "kt": KT_SCALAR}[lang][ty[0]]
    name = vec_name(ty[0], ty[1]) if len(ty) == 2 else mat_name(*ty)
    if lang == "c":
        return "Koral" + name
    if lang == "cpp":
        return f"kor::Vec<{CPP_SCALAR[ty[0]]}, {ty[1]}>" if len(ty) == 2 else f"kor::Mat<{CPP_SCALAR[ty[0]]}, {ty[1]}, {ty[2]}>"
    return name


def c_prefix(ty):
    if len(ty) == 1:
        return C_PREFIX[ty[0]]
    return (vec_name(*ty) if len(ty) == 2 else mat_name(*ty)).lower()


# ---- function instances -------------------------------------------------------------------------------------

class Param:
    def __init__(self, name, ty, mode, default, mapped):
        self.name, self.ty, self.mode, self.default, self.mapped = name, ty, mode, default, mapped   # mode: "", "out", "ref"


class Inst:
    def __init__(self, fn, t, n, params, ret, how, bcast=False):
        self.fn, self.t, self.n, self.params, self.ret, self.how, self.bcast = fn, t, n, params, ret, how, bcast


def resolve(kind, t, n, mapped):
    """A spec kind as a type, in the scalar function (mapped=False) or its vector form of size n."""
    fixed = {"int": ("i",), "bool": ("b",), "u32": ("u",), "i32": ("i",), "f32": ("f",), "f64": ("d",), "u16": ("h",),
             "f2": ("f", 2), "f4": ("f", 4), "u2": ("u", 2), "void": None}
    if kind == "T":
        return (t, n) if mapped else (t,)
    if kind == "int*":
        return ("i", n) if mapped else ("i",)
    if mapped and kind in ("bool", "u32", "i32", "f32", "int"):
        return (fixed[kind][0], n)
    if kind in fixed:
        return fixed[kind]
    m = re.fullmatch(r"(B|I)?V(\d)?", kind)
    if m:
        code = {"B": "b", "I": "i", None: t}[m.group(1)]
        return (code, int(m.group(2)) if m.group(2) else n)
    raise SystemExit(f"unknown kind {kind}")


def instances():
    out = []
    for fn in spec.FNS:
        kinds = [k.rstrip("&@") for _, k, _ in fn.params] + [fn.ret]
        sized = any(re.fullmatch(r"(B|I)?V", k) for k in kinds)
        for t in fn.types:
            def make(n, mapped, how, bcast=False):
                params = []
                for name, kind, default in fn.params:
                    mode = "out" if kind.endswith("&") else "ref" if kind.endswith("@") else ""
                    k = kind.rstrip("&@")
                    is_mapped = mapped and (k in ("T", "int*") or (mode and k == "int")) and not (bcast and name in fn.bcast)
                    params.append(Param(name, resolve(k, t, n, is_mapped), mode, default, is_mapped))
                return Inst(fn, t, n, params, resolve(fn.ret, t, n, mapped) if fn.ret != "void" else None, how, bcast)
            if sized:
                for n in fn.sizes:
                    out.append(make(n, False, "body"))
            else:
                fixed = [int(m.group(1)) for k in kinds if (m := re.fullmatch(r"(?:B|I)?V(\d)", k))]
                out.append(make(fixed[0] if fixed else None, False, "body"))
            if fn.map:
                for n in (2, 3, 4):
                    out.append(make(n, True, "map"))
                    if fn.bcast:
                        out.append(make(n, True, "map", bcast=True))
    return out


INSTANCES = instances()


def c_name(inst):
    fn = inst.fn
    if fn.chapter.startswith("packing"):
        return "koral_" + snake(fn.name)
    vecs = [p.ty for p in inst.params if len(p.ty) > 1] + ([inst.ret] if inst.ret and len(inst.ret) > 1 else [])
    vec = next((v for v in vecs if v[0] == inst.t), None) or next(iter(vecs), None)
    prefix = c_prefix(vec) if vec else C_PREFIX[inst.t]
    return f"koral_{prefix}_{snake(fn.name)}{'_s' if inst.bcast else ''}"


# ---- swizzles (C++) -----------------------------------------------------------------------------------------

def swizzles(n):
    """Every read swizzle of an n-component vector: 2 to 4 components, repeats allowed."""
    letters = "xyzw"[:n]
    for length in (2, 3, 4):
        for combo in itertools.product(letters, repeat=length):
            yield "".join(combo)


def cpp_swizzles():
    for n in (2, 3, 4):
        lines = [f"// <auto-generated> by scripts/kmath/generate.py: do not edit. </auto-generated>",
                 f"// Included inside kor::Vec<T, {n}>: every read swizzle, as glm's GLM_FORCE_SWIZZLE has them — v.ZYX(), v.XXYY().", ""]
        for s in swizzles(n):
            args = ", ".join(s)
            lines.append(f"constexpr Vec<T, {len(s)}> {s.upper()}() const {{ return {{{args}}}; }}")
        emit(f"include/kmath/detail/swizzle{n}.inl", "\n".join(lines) + "\n")


# ---- C ------------------------------------------------------------------------------------------------------

MATS = [(t, c, r) for t in "fd" for c in (2, 3, 4) for r in (2, 3, 4)]
VECS = [(t, n) for t in SCALARS for n in (2, 3, 4)]


def c_param(p):
    ty = type_name("c", p.ty)
    return f"{ty}* {p.name}" if p.mode else f"{ty} {p.name}"


def c_ret(inst):
    return type_name("c", inst.ret) if inst.ret else "void"


def matrix_c_functions():
    """(declaration, C++ body) of the matrix exports."""
    out = []

    def add(ret, name, params, body):
        out.append((ret, name, params, body))

    for t, c, r in MATS:
        M, p = type_name("c", (t, c, r)), c_prefix((t, c, r))
        col, row, s = type_name("c", (t, r)), type_name("c", (t, c)), C_SCALAR[t]
        if c == r:
            add(M, f"koral_{p}_identity", "void", f"return C({type_name('cpp', (t, c, r))}(1));")
            add(s, f"koral_{p}_determinant", f"{M} m", "return kor::Determinant(K(m));")
            add(M, f"koral_{p}_inverse", f"{M} m", "return C(kor::Inverse(K(m)));")
            add(M, f"koral_{p}_diagonal", f"{col} v", "return C(kor::Diagonal(K(v)));")
        for k in (2, 3, 4):   # this (c columns, r rows) * (k columns, c rows)
            other, res = (t, k, c), (t, k, r)
            name = f"koral_{p}_mul" if (k, c) == (c, r) and c == r else f"koral_{p}_mul_{c_prefix(other)}"
            add(type_name("c", res), name, f"{M} a, {type_name('c', other)} b", "return C(K(a) * K(b));")
        add(col, f"koral_{p}_mul_{c_prefix((t, c))}", f"{M} m, {row} v", "return C(K(m) * K(v));")
        add(row, f"koral_{c_prefix((t, r))}_mul_{p}", f"{col} v, {M} m", "return C(K(v) * K(m));")
        add(M, f"koral_{p}_add", f"{M} a, {M} b", "return C(K(a) + K(b));")
        add(M, f"koral_{p}_sub", f"{M} a, {M} b", "return C(K(a) - K(b));")
        add(M, f"koral_{p}_negate", f"{M} m", "return C(-K(m));")
        add(M, f"koral_{p}_mul_s", f"{M} m, {s} s", "return C(K(m) * s);")
        add(M, f"koral_{p}_div_s", f"{M} m, {s} s", "return C(K(m) / s);")
        add("bool", f"koral_{p}_eq", f"{M} a, {M} b", "return K(a) == K(b);")
        add(type_name("c", (t, r, c)), f"koral_{p}_transpose", f"{M} m", "return C(kor::Transpose(K(m)));")
        add(M, f"koral_{p}_matrix_comp_mult", f"{M} a, {M} b", "return C(kor::MatrixCompMult(K(a), K(b)));")
        add(M, f"koral_{p}_outer_product", f"{col} column, {row} row", "return C(kor::OuterProduct(K(column), K(row)));")
        add(row, f"koral_{p}_row", f"{M} m, int32_t r", "return C(kor::Row(K(m), r));")
        add(col, f"koral_{p}_column", f"{M} m, int32_t c", "return C(kor::Column(K(m), c));")
        add(M, f"koral_{p}_set_row", f"{M} m, int32_t r, {row} value", "return C(kor::Row(K(m), r, K(value)));")
        add(M, f"koral_{p}_set_column", f"{M} m, int32_t c, {col} value", "return C(kor::Column(K(m), c, K(value)));")
        add("bool", f"koral_{p}_approx_equal", f"{M} a, {M} b, {s} epsilon", "return kor::ApproxEqual(K(a), K(b), epsilon);")
        for t2, c2, r2 in MATS:
            if (t2, c2, r2) != (t, c, r) and (t2 == t or (c2, r2) == (c, r)):
                add(M, f"koral_{p}_from_{c_prefix((t2, c2, r2))}", f"{type_name('c', (t2, c2, r2))} m",
                    f"return C({type_name('cpp', (t, c, r))}(K(m)));")
    for t in "fd":
        p3, p4 = c_prefix((t, 3, 3)), c_prefix((t, 4, 4))
        add(type_name("c", (t, 3, 3)), f"koral_{p4}_normal_matrix", f"{type_name('c', (t, 4, 4))} model", "return C(kor::NormalMatrix(K(model)));")
        add(type_name("c", (t, 3, 3)), f"koral_{p3}_orthonormalize", f"{type_name('c', (t, 3, 3))} m", "return C(kor::Orthonormalize(K(m)));")
    return out


MATRIX_C = matrix_c_functions()


def c_header_section():
    L = [HEADER_C, "/* The vector and matrix types, and kmath's GLSL chapters: see scripts/kmath/spec.py. */", ""]
    L.append("/* ==== constants (glm's gtc/constants): KORAL_PI is the double, KORAL_PI_F the float ==== */")
    for name, dv, fv, _ in spec.CONSTANTS:
        macro = "KORAL_" + snake(name).upper()
        L.append(f"#define {macro} {dv!r}")
        L.append(f"#define {macro}_F {fv!r}f")
    L += ["", "/* ==== vector types: C++'s kor::Vec<T, N>, member for member ==== */", ""]
    for t, n in VECS:
        L.append(f"typedef struct {type_name('c', (t, n))} {{ {C_SCALAR[t]} {', '.join(XYZW[:n])}; }} {type_name('c', (t, n))};")
    L += ["", "/* ==== matrix types: C columns of R rows, column after column: m[column * R + row] ==== */", ""]
    for t, c, r in MATS:
        L.append(f"typedef struct {type_name('c', (t, c, r))} {{ {C_SCALAR[t]} m[{c * r}]; }} {type_name('c', (t, c, r))};")
    for t in "fd":
        for n in (2, 3, 4):
            L.append(f"typedef {type_name('c', (t, n, n))} Koral{MAT_PREFIX[t]}Mat{n}x{n};")
    L += ["", "/* ==== vector construction and arithmetic (inline): component by component, as C++'s operators ==== */", ""]
    for t, n in VECS:
        V, p, s = type_name("c", (t, n)), c_prefix((t, n)), C_SCALAR[t]
        comps = XYZW[:n]
        args = ", ".join(f"{s} {c}" for c in comps)
        L.append(f"static inline {V} koral_{p}({args}) {{ {V} r = {{{', '.join(comps)}}}; return r; }}")
        L.append(f"static inline {V} koral_{p}_splat({s} s) {{ {V} r = {{{', '.join('s' for _ in comps)}}}; return r; }}")
        ops = []
        if t != "b":
            ops += [("add", "+"), ("sub", "-"), ("mul", "*"), ("div", "/")]
        if t in "iu":
            ops += [("rem", "%"), ("bit_and", "&"), ("bit_or", "|"), ("bit_xor", "^"), ("shl", "<<"), ("shr", ">>")]
        if t == "b":
            ops += [("logical_and", "&&"), ("logical_or", "||")]
        for name, op in ops:
            cast = f"({s})" if t != "b" else ""
            L.append(f"static inline {V} koral_{p}_{name}({V} a, {V} b) {{ return koral_{p}({', '.join(f'{cast}(a.{c} {op} b.{c})' for c in comps)}); }}")
            if t != "b":
                L.append(f"static inline {V} koral_{p}_{name}_s({V} a, {s} s) {{ return koral_{p}({', '.join(f'{cast}(a.{c} {op} s)' for c in comps)}); }}")
        if t in "fdi":
            L.append(f"static inline {V} koral_{p}_negate({V} a) {{ return koral_{p}({', '.join(f'-a.{c}' for c in comps)}); }}")
        if t in "iu":
            L.append(f"static inline {V} koral_{p}_bit_not({V} a) {{ return koral_{p}({', '.join(f'({s})~a.{c}' for c in comps)}); }}")
        L.append(f"static inline bool koral_{p}_eq({V} a, {V} b) {{ return {' && '.join(f'a.{c} == b.{c}' for c in comps)}; }}")
        for t2 in SCALARS:
            if t2 != t:
                L.append(f"static inline {V} koral_{p}_from_{c_prefix((t2, n))}({type_name('c', (t2, n))} v) "
                         f"{{ return koral_{p}({', '.join(f'({s})v.{c}' for c in comps)}); }}")
        for m in range(n + 1, 5):
            L.append(f"static inline {V} koral_{p}_from_{c_prefix((t, m))}({type_name('c', (t, m))} v) {{ return koral_{p}({', '.join(f'v.{c}' for c in comps)}); }}")
        L.append("")
    chapter = None
    for inst in INSTANCES:
        if not inst.fn.c:
            continue
        if inst.fn.chapter != chapter:
            chapter = inst.fn.chapter
            L += ["", f"/* ==== {chapter} ==== */"]
        L.append(f"KORAL_API {c_ret(inst)} {c_name(inst)}({', '.join(c_param(p) for p in inst.params) or 'void'});")
    L += ["", "/* ==== matrices (kmath/matrix.h): koral_<a>_mul_<b> is a * b; _s takes a scalar ==== */"]
    for ret, name, params, _ in MATRIX_C:
        L.append(f"KORAL_API {ret} {name}({params});")
    L += material_c_types()
    L += ["", "/* ==== Euler angles by name (kmath/euler.h): koral_euler_angle_xyz(a, b, c) is X(a) * Y(b) * Z(c) ==== */"]
    L += euler_c()[0]
    return "\n".join(L) + "\n"


def c_source():
    L = [HEADER_C.replace("/*", "//", 1).replace(" */", ""), "// The C exports of kmath's GLSL chapters and matrices: each a C++ template, its C structs bit-cast.", "",
         "#include \"koral_math_c.h\"", "", "#include <kmath.h>", "", "#include <bit>", "", "namespace {",
         "    template<class T> requires std::is_arithmetic_v<T> T K(T v) { return v; }",
         "    template<class T> requires std::is_arithmetic_v<T> T C(T v) { return v; }"]
    for t, n in VECS:
        L.append(f"    {type_name('cpp', (t, n))} K({type_name('c', (t, n))} v) {{ return std::bit_cast<{type_name('cpp', (t, n))}>(v); }}")
        L.append(f"    {type_name('c', (t, n))} C(const {type_name('cpp', (t, n))}& v) {{ return std::bit_cast<{type_name('c', (t, n))}>(v); }}")
    for ty in MATS:
        L.append(f"    {type_name('cpp', ty)} K({type_name('c', ty)} v) {{ return std::bit_cast<{type_name('cpp', ty)}>(v); }}")
        L.append(f"    {type_name('c', ty)} C(const {type_name('cpp', ty)}& v) {{ return std::bit_cast<{type_name('c', ty)}>(v); }}")
    L += ["}", "", "extern \"C\" {", ""]
    for inst in INSTANCES:
        if not inst.fn.c:
            continue
        pre, args, post = [], [], []
        for p in inst.params:
            if p.mode:
                local = f"o_{p.name}"
                init = f"K(*{p.name})" if p.mode == "ref" else f"{type_name('cpp', p.ty)}{{}}"
                pre.append(f"auto {local} = {init};")
                args.append(local)
                post.append(f"*{p.name} = C({local});")
            else:
                args.append(f"K({p.name})")
        call = f"kor::{inst.fn.name}({', '.join(args)})"
        sig = f"{c_ret(inst)} {c_name(inst)}({', '.join(c_param(p) for p in inst.params) or 'void'})"
        if not pre and inst.ret:
            L.append(f"{sig} {{ return C({call}); }}")
        elif not inst.ret:
            L.append(f"{sig} {{ {' '.join(pre)} {call}; {' '.join(post)} }}")
        else:
            L.append(f"{sig} {{ {' '.join(pre)} const auto r = {call}; {' '.join(post)} return C(r); }}")
    L.append("")
    for ret, name, params, body in MATRIX_C:
        L.append(f"{ret} {name}({params}) {{ {body} }}")
    L += [""] + euler_c()[1]
    L += ["", "}", ""]
    return "\n".join(L)


def check_c_names():
    seen = {}
    for inst in INSTANCES:
        if inst.fn.c:
            name = c_name(inst)
            if name in seen:
                raise SystemExit(f"two C functions named {name}")
            seen[name] = inst
    for _, name, _, _ in MATRIX_C:
        if name in seen:
            raise SystemExit(f"two C functions named {name}")
        seen[name] = None


def splice_header():
    path = ROOT / "include/koral_math_c.h"
    text = path.read_text()
    begin, end = "/* ==== BEGIN generated by scripts/kmath/generate.py ==== */\n", "/* ==== END generated ==== */\n"
    a, b = text.index(begin) + len(begin), text.index(end)
    emit("include/koral_math_c.h", text[:a] + c_header_section() + text[b:])



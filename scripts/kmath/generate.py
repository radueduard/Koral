def material_c_types():
    L = ["", "/* ==== Material colours (kmath/material.h) ==== */",
         "/* The 2014 palette as 0xRRGGBB (sRGB): koral_color_from_hex(KORAL_MATERIAL_RED_500). */"]
    for name, value in palette_entries():
        m = re.fullmatch(r"([A-Za-z]+?)(A?\d+)?", name)
        macro = snake(m.group(1)).upper() + (f"_{m.group(2)}" if m.group(2) else "")
        L.append(f"#define KORAL_MATERIAL_{macro} {value}u")
    L.append("typedef enum KoralMaterialHue { " + ", ".join(f"KORAL_MATERIAL_HUE_{snake(h).upper()}" + (" = 0" if i == 0 else "") for i, h in enumerate(HUES)) + " } KoralMaterialHue;")

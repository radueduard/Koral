def kt_function(inst, documented):
    L = []
    if inst.fn.doc and inst.fn.doc not in documented:
        documented.add(inst.fn.doc)
        L.append(f"/** {inst.fn.doc} */")
    name = lower_camel(inst.fn.name)
    scalar_only = all(len(p.ty) == 1 for p in inst.params) and (not inst.ret or len(inst.ret) == 1)
    private = scalar_only and inst.t in KT_CLASH.get(name, "")
    params = []
    for p in inst.params:
        ty = type_name("kt", p.ty)
        s = f"{p.name}: {'Ref<' + ty + '>' if p.mode else ty}"
        if p.default:
            s += f" = {default_value('kt', p)}"
        params.append(s)
    ret = type_name("kt", inst.ret) if inst.ret else "Unit"
    sig = f"{'private ' if private else ''}fun {name}({', '.join(params)}): {ret}"
    if inst.how == "map":
        n = inst.n
        outs = [p for p in inst.params if p.mode]
        calls = []
        for c in XYZW[:n]:
            args = []
            for p in inst.params:
                if p.mode:
                    args.append(f"{p.name}{c.upper()}")
                elif p.mapped:
                    args.append(f"{p.name}.{c}")
                else:
                    args.append(p.name)
            calls.append(f"{name}({', '.join(args)})")
        if not outs:
            L.append(f"{sig} = {type_name('kt', inst.ret)}({', '.join(calls)})")
        else:
            L.append(sig + " {")
            for p in outs:
                for c in XYZW[:n]:
                    L.append(f"    val {p.name}{c.upper()} = Ref({zero_of('kt', (p.ty[0],))})")
            if inst.ret:
                L.append(f"    val r = {type_name('kt', inst.ret)}({', '.join(calls)})")
            else:
                L += [f"    {c}" for c in calls]
            for p in outs:
                L.append(f"    {p.name}.value = {type_name('kt', p.ty)}({', '.join(p.name + c.upper() + '.value' for c in XYZW[:n])})")
            if inst.ret:
                L.append("    return r")
            L.append("}")
        return L
    if inst.fn.raw:
        lines = raw_body(inst, "kt")
        if len(lines) == 1 and lines[0].startswith("="):
            L.append(f"{sig} = {lines[0][1:]}")
        else:
            L += [sig + " {"] + [f"    {line}" for line in lines] + ["}"]
        return L
    lines = dsl.body("kt", inst.t, inst.n, dsl_body(inst), 4)
    if len(lines) == 1 and lines[0].strip().startswith("return "):
        L.append(f"{sig} = {lines[0].strip()[7:]}")
    else:
        L += [sig + " {"] + lines + ["}"]
    return L


